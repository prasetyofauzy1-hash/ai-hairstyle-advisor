"""Sanity review of the Phase 4 rule engine: top-5 per face shape x hair type x gender, plus automated checks over
every shape x hair type x thickness x gender combination. Writes research/results/phase4/sanity_review.md.

This is a mechanical consistency check plus a table for a human to read; it is not a user or stylist evaluation.

    python -m ml.recommendation.review
"""

from __future__ import annotations

import itertools
from pathlib import Path

from ml.classification.rule_based import SHAPE_LABELS_ID, SHAPES
from ml.recommendation import rules as R
from ml.recommendation.catalog import HAIR_TYPES, LABELS_ID, THICKNESSES, load_catalog
from ml.recommendation.engine import UserProfile, recommend

OUT = Path(__file__).resolve().parents[2] / "research/results/phase4/sanity_review.md"


def grid_checks() -> dict:
    by_id = {s.id: s for s in load_catalog()}
    combos = short = violations = 0
    short_cases = []
    for shape, hair, thick, gender in itertools.product(SHAPES, HAIR_TYPES, THICKNESSES, (None, "pria", "wanita")):
        combos += 1
        recs = recommend(UserProfile(shape, hair, thick, gender=gender))["recommendations"]
        if len(recs) < 5:
            short += 1
            short_cases.append(f"{shape} / {hair} / {thick} / {gender or 'semua'}: {len(recs)}")
        for r in recs:
            s = by_id[r["id"]]
            ok = (hair in s.hair_types and (gender is None or gender in s.gender)
                  and R.shape_points(shape, s.effects) >= 0
                  and r["score"] == sum(b["points"] for b in r["score_breakdown"]))
            violations += not ok
    return {"combos": combos, "short": short, "short_cases": short_cases, "violations": violations}


def render() -> str:
    g = grid_checks()
    lines = [
        "# Phase 4 sanity review: top-5 per face shape × hair type",
        "",
        "Generated by `python -m ml.recommendation.review` from `ml/recommendation/catalog.json` (rule_based_v1).",
        "Scores are rule points, not percentages or probabilities. Nothing here is a user, stylist, or preference evaluation.",
        "",
        "## Automated checks over the full grid",
        "",
        f"- Profiles checked (6 shapes × 4 hair types × 3 thicknesses × {{semua, pria, wanita}}): {g['combos']}",
        f"- Returned results violating a filter (hair type, gender, negative face-shape points) or with a score that "
        f"differs from its breakdown: {g['violations']}",
        f"- Profiles with fewer than 5 results: {g['short']}",
    ]
    lines += [f"  - {c}" for c in g["short_cases"]]
    lines += ["", "## Top-5 tables (thickness: sedang, no length or other preference)", ""]
    for shape in SHAPES:
        lines += [f"### {SHAPE_LABELS_ID[shape]} (`{shape}`)", "", "| Rambut | Gender | Top-5 (skor poin) |", "|---|---|---|"]
        for hair, gender in itertools.product(HAIR_TYPES, ("pria", "wanita")):
            recs = recommend(UserProfile(shape, hair, "medium", gender=gender))["recommendations"]
            cell = "; ".join(f"{r['name']} ({r['score']})" for r in recs) or "—"
            lines.append(f"| {LABELS_ID[hair]} | {gender} | {cell} |")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
